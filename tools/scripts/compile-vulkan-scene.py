#!/usr/bin/env python3
"""Compile the Vulkan hardware scene shaders into their embedded SPIR-V header."""

import argparse
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[2]
DIRECTORY = ROOT / "src/restunts/c/renderer"
HEADER = DIRECTORY / "vulkan_scene_spirv.h"
STAGES = (("vertex", "vert"), ("fragment", "frag"))
WORDS_PER_LINE = 7
SPIRV_MAGIC = 0x07230203


def source_digest(extension):
    source = (DIRECTORY / f"vulkan_scene.{extension}").read_bytes()
    return hashlib.sha256(source.replace(b"\r\n", b"\n")).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", default="glslangValidator")
    parser.add_argument("--check", action="store_true",
                        help="Check that source hashes match the embedded shaders")
    arguments = parser.parse_args()
    markers = {stage: f" * {stage} SHA-256: {source_digest(extension)}"
               for stage, extension in STAGES}
    if arguments.check:
        header = HEADER.read_text(encoding="ascii") if HEADER.is_file() else ""
        if any(marker not in header for marker in markers.values()):
            parser.error("Vulkan scene header is stale; run tools/scripts/compile-vulkan-scene.py")
        print("Vulkan scene shaders and embedded SPIR-V are current.")
        return

    lines = ["/* Generated by tools/scripts/compile-vulkan-scene.py; do not edit.",
             *markers.values(), " */", "#ifndef RESTUNTS_VULKAN_SCENE_SPIRV_H",
             "#define RESTUNTS_VULKAN_SCENE_SPIRV_H", "", '#include "../legacy.h"',
             "#include <stddef.h>", ""]
    with tempfile.TemporaryDirectory(prefix="restunts-vulkan-scene-") as temporary:
        for stage, extension in STAGES:
            output = Path(temporary) / f"{stage}.spv"
            subprocess.run([arguments.compiler, "-V", "--target-env", "vulkan1.0",
                            str(DIRECTORY / f"vulkan_scene.{extension}"), "-o", str(output)],
                           check=True)
            data = output.read_bytes()
            if len(data) % 4:
                raise ValueError("SPIR-V contains incomplete words")
            words = struct.unpack("<" + "I" * (len(data) // 4), data)
            if not words or words[0] != SPIRV_MAGIC:
                raise ValueError("Compiler did not produce SPIR-V")
            symbol = f"vulkan_scene_{stage}_spirv"
            lines.append(f"static const legacy_u32 {symbol}[] = {{")
            for start in range(0, len(words), WORDS_PER_LINE):
                lines.append("\t" + ", ".join(f"0x{word:08x}U"
                             for word in words[start:start + WORDS_PER_LINE]) + ",")
            lines += ["};", f"static const size_t {symbol}_size = sizeof({symbol});", ""]
    lines += ["#endif", ""]
    HEADER.write_bytes("\r\n".join(lines).encode("ascii"))


if __name__ == "__main__":
    main()
