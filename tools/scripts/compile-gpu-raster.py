#!/usr/bin/env python3
"""Compile the checked-in Vulkan raster shader into its portable SPIR-V header."""

import argparse
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src/restunts/c/renderer/gpu_raster.comp"
HEADER = SOURCE.with_name("gpu_raster_spirv.h")
WORDS_PER_LINE = 7
SPIRV_MAGIC = 0x07230203


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", default="glslangValidator")
    parser.add_argument("--check", action="store_true",
                        help="Check that the generated header matches the shader source hash")
    args = parser.parse_args()
    # Git may materialize shader text with CRLF on a Windows developer's machine.
    digest = hashlib.sha256(SOURCE.read_bytes().replace(b"\r\n", b"\n")).hexdigest()
    if args.check:
        marker = f" * Shader SHA-256: {digest} */"
        if not HEADER.is_file() or marker not in HEADER.read_text(encoding="ascii"):
            parser.error("SPIR-V header is stale; regenerate it after editing gpu_raster.comp")
        print("Vulkan shader source and generated SPIR-V header are current.")
        return
    with tempfile.TemporaryDirectory(prefix="restunts-shader-") as temporary:
        output = Path(temporary) / "gpu_raster.spv"
        subprocess.run([args.compiler, "-V", "--target-env", "vulkan1.0", str(SOURCE),
                        "-o", str(output)], check=True)
        data = output.read_bytes()
    if len(data) % 4:
        raise ValueError("SPIR-V contains incomplete words")
    words = struct.unpack("<" + "I" * (len(data) // 4), data)
    if not words or words[0] != SPIRV_MAGIC:
        raise ValueError("Compiler did not produce SPIR-V")
    lines = ["/* Generated by tools/scripts/compile-gpu-raster.py; do not edit.",
             f" * Shader SHA-256: {digest} */",
             "#ifndef RESTUNTS_GPU_RASTER_SPIRV_H", "#define RESTUNTS_GPU_RASTER_SPIRV_H", "",
             '#include "../legacy.h"', "#include <stddef.h>", "",
             "static const legacy_u32 gpu_raster_spirv[] = {"]
    for start in range(0, len(words), WORDS_PER_LINE):
        lines.append("\t" + ", ".join(f"0x{word:08x}U" for word in words[start:start + WORDS_PER_LINE]) + ",")
    lines += ["};", "static const size_t gpu_raster_spirv_size = sizeof(gpu_raster_spirv);", "",
              "#endif", ""]
    HEADER.write_bytes("\r\n".join(lines).encode("ascii"))


if __name__ == "__main__":
    main()
