#!/usr/bin/env python3
"""Keep the offline editor's route catalog identical to the compiled game tables."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'src/restunts/c/headless_trackdata.c'
OUTPUT = ROOT / 'src/restunts/platform/wasm/track-editor-route-data.js'


def records(source, name, count):
    match = re.search(r'\b' + name + r'\[' + str(count) + r'\] = \{(.*?)\n\};', source, re.S)
    if not match:
        raise ValueError('Cannot find catalog ' + name)
    rows = re.findall(r'\{([^{}]+)\}', match[1])
    if len(rows) != count:
        raise ValueError('Unexpected catalog length: ' + name)
    return [[field.strip() for field in row.split(',')] for row in rows]


def generate():
    source = SOURCE.read_text()
    blocks = []
    for row in records(source, 'legacy_track_info', 120):
        if len(row) != 12:
            raise ValueError('Unexpected route block fields')
        blocks.append(dict(zip(('count', 'entry', 'exit', 'entryType', 'exitType', 'sign'),
                               [int(row[i]) for i in (0, 1, 2, 3, 4, 10)])))
    objects = []
    for row in records(source, 'trkObjectList', 215):
        if len(row) != 10:
            raise ValueError('Unexpected object fields')
        route = re.fullmatch(r'&legacy_track_info\[(\d+)\]', row[0])
        if not route and row[0] != '0':
            raise ValueError('Unexpected route pointer')
        shapes = [re.fullmatch(r'TRACK_SHAPE\((\d+)\)', row[i]) for i in (2, 3)]
        if any(not shape and row[i] != '0' for shape, i in zip(shapes, (2, 3))):
            raise ValueError('Unexpected shape pointer')
        objects.append(dict(routeIndex=int(route[1]) if route else None,
                            rotation=int(row[1]) // 256,
                            shape=int(shapes[0][1]) if shapes[0] else None,
                            lowShape=int(shapes[1][1]) if shapes[1] else None,
                            surface=int(row[5]), flags=int(row[7]), physical=int(row[8])))
    def array(rows):
        return ',\n'.join('        ' + json.dumps(row, separators=(',', ':')) for row in rows)
    return '''/* Generated by tools/scripts/generate-editor-route-data.py from
 * headless_trackdata.c. Route metadata only; no game artwork is included. */
(function (root, factory) {
    const api = factory();
    if (typeof module === 'object' && module.exports) module.exports = api;
    else root.TrackEditorRouteData = api;
}(typeof globalThis !== 'undefined' ? globalThis : this, function () {
    'use strict';
    return { blocks: [
''' + array(blocks) + '''
    ], objects: [
''' + array(objects) + '''
    ] };
}));
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Reject out-of-date generated data')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            parser.error('Editor route data is out of date; run this script without --check')
        print('Editor route data matches the compiled game catalog.')
    else:
        OUTPUT.write_text(content)
