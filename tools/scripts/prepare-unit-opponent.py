#!/usr/bin/env python3
"""Reduce the preserved UNIT pixel-art portrait to the exact Stunts VGA palette."""

import argparse
import hashlib
import json
from pathlib import Path
import runpy

from PIL import Image


ROOT = Path(__file__).resolve().parents[2]
TILE_SIZE = (80, 83)
PHOTO_POSITION = (2, 2)
PHOTO_SIZE = (74, 79)
OUTPUT_SCALE = 2
DIGIT_POSITION = (66, 4)
DIGIT_COLOR = 39
# Match the original opponents' top and right seven-segment strokes and gaps.
DIGIT_SEVEN = (
    "011110", "000001", "000001", "000001", "000000",
    "000001", "000001", "000001", "000000",
)
DIGIT_SIZE = (len(DIGIT_SEVEN[0]), len(DIGIT_SEVEN))
HEADER_BYTES_PER_LINE = 16


def digest(data):
    return hashlib.sha256(data).hexdigest()


def portrait_header(pixels, result_patch):
    lines = [
        "/* Generated by tools/scripts/prepare-unit-opponent.py. Do not edit by hand. */",
        "#ifndef RESTUNTS_UNIT_PORTRAIT_DATA_H",
        "#define RESTUNTS_UNIT_PORTRAIT_DATA_H",
        "",
        '#include "../legacy.h"',
        "",
        f"#define UNIT_PORTRAIT_WIDTH {TILE_SIZE[0]}U",
        f"#define UNIT_PORTRAIT_HEIGHT {TILE_SIZE[1]}U",
        f"#define UNIT_PORTRAIT_DIGIT_X {DIGIT_POSITION[0]}U",
        f"#define UNIT_PORTRAIT_DIGIT_Y {DIGIT_POSITION[1]}U",
        f"#define UNIT_PORTRAIT_DIGIT_WIDTH {DIGIT_SIZE[0]}U",
        f"#define UNIT_PORTRAIT_DIGIT_HEIGHT {DIGIT_SIZE[1]}U",
        "",
        "// clang-format off",
        "static const legacy_u8 unit_portrait_pixels[UNIT_PORTRAIT_WIDTH * UNIT_PORTRAIT_HEIGHT] = {",
    ]
    for offset in range(0, len(pixels), HEADER_BYTES_PER_LINE):
        values = pixels[offset:offset + HEADER_BYTES_PER_LINE]
        lines.append("\t" + ", ".join(f"{value:3}" for value in values) + ",")
    lines.extend([
        "};",
        "",
        "/* Original photo pixels beneath the selection-screen numeral. */",
        "static const legacy_u8",
        "\tunit_portrait_result_patch[UNIT_PORTRAIT_DIGIT_WIDTH * UNIT_PORTRAIT_DIGIT_HEIGHT] = {",
    ])
    for offset in range(0, len(result_patch), HEADER_BYTES_PER_LINE):
        values = result_patch[offset:offset + HEADER_BYTES_PER_LINE]
        lines.append("\t" + ", ".join(f"{value:3}" for value in values) + ",")
    lines.extend(["};", "// clang-format on", "", "#endif", ""])
    return "\r\n".join(lines).encode("ascii")


def generate(repository, source):
    helpers = runpy.run_path(str(repository / "tools/scripts/extract-skyboxes.py"))
    unpack = runpy.run_path(
        str(repository / "tools/scripts/generate-owoot-road-geometry.py")
    )["unpack"]
    palette_resource = (repository / "stunts/SDMAIN.PVS").read_bytes()
    palette_shape = helpers["resource_shapes"](unpack(palette_resource))["!pal"]
    palette_vga = palette_shape[helpers["SHAPE_HEADER_SIZE"]:]
    if len(palette_vga) != helpers["VGA_PALETTE_SIZE"]:
        raise ValueError("Expected the original 256-color VGA palette")
    palette_rgb = bytes((value & helpers["VGA_COMPONENT_MAX"]) * helpers["RGB_COMPONENT_MAX"]
                        // helpers["VGA_COMPONENT_MAX"] for value in palette_vga)
    palette = Image.new("P", (1, 1))
    palette.putpalette(palette_rgb)
    with Image.open(source) as original:
        source_size = original.size
        photo = original.convert("RGB").resize(PHOTO_SIZE, Image.Resampling.BOX)
    photo = photo.quantize(palette=palette, dither=Image.Dither.NONE)

    # Retain the original indexed tile border and positioning proportions.
    shape_resource = (repository / "stunts/SDOSEL.PVS").read_bytes()
    template = helpers["resource_shapes"](unpack(shape_resource))["opp6"]
    width, height, original_pixels = helpers["bitmap"](template)
    if (width, height) != TILE_SIZE:
        raise ValueError("Unexpected original opponent tile dimensions")
    tile = Image.frombytes("P", TILE_SIZE, original_pixels)
    tile.putpalette(palette_rgb)
    tile.paste(photo, PHOTO_POSITION)
    result_patch = tile.crop((
        *DIGIT_POSITION,
        DIGIT_POSITION[0] + DIGIT_SIZE[0],
        DIGIT_POSITION[1] + DIGIT_SIZE[1],
    )).tobytes()
    for row, line in enumerate(DIGIT_SEVEN):
        for column, value in enumerate(line):
            if value == "1":
                tile.putpixel((DIGIT_POSITION[0] + column, DIGIT_POSITION[1] + row), DIGIT_COLOR)

    pixels = tile.tobytes()
    enlarged = tile.resize(tuple(value * OUTPUT_SCALE for value in TILE_SIZE),
                           Image.Resampling.NEAREST)
    tile_png = helpers["indexed_png"](*TILE_SIZE, pixels, palette_rgb)
    enlarged_png = helpers["indexed_png"](*enlarged.size, enlarged.tobytes(), palette_rgb)
    outputs = {
        "assets/opponents/game/opp7.png": enlarged_png,
        "docs/opponents/game-sources/native/opp7.png": tile_png,
        "src/restunts/c/opponent/unit_portrait_data.h": portrait_header(pixels, result_patch),
    }
    manifest = {
        "generator": "tools/scripts/prepare-unit-opponent.py",
        "opponent": 7,
        "identifier": "UNIT",
        "source": "docs/opponents/game-sources/full-resolution/opp7.png",
        "source_size": list(source_size),
        "source_sha256": digest(source.read_bytes()),
        "palette_source": "SDMAIN.PVS:!pal",
        "palette_source_sha256": digest(palette_resource),
        "palette_rgb_sha256": digest(palette_rgb),
        "native_size": list(TILE_SIZE),
        "photo_size": list(PHOTO_SIZE),
        "runtime_size": list(enlarged.size),
        "pixel_sha256": digest(pixels),
        "runtime_sha256": digest(enlarged_png),
        "colors_used": len(set(pixels)),
        "processing": [
            "Imagegen restyled the supplied Unitree reference as pixel art",
            "BOX reduction to 74 x 79 portrait pixels",
            "Quantize to exact SDMAIN VGA palette without dithering",
            "Preserve original frame and apply a matching seven-segment numeral 7",
            "Nearest-neighbor 2x enlargement for enhanced portrait asset",
        ],
    }
    outputs["assets/opponents/game/unit-manifest.json"] = (
        json.dumps(manifest, indent=2) + "\n"
    ).encode("utf-8")
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository-root", type=Path, default=ROOT)
    parser.add_argument("--source", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = args.source or args.repository_root / "docs/opponents/game-sources/full-resolution/opp7.png"
    try:
        outputs = generate(args.repository_root, source)
        for name, data in outputs.items():
            destination = args.repository_root / name
            if args.check:
                if destination.read_bytes() != data:
                    raise ValueError(f"UNIT artwork differs: {destination}")
            else:
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(data)
        print("Verified UNIT artwork" if args.check else "Prepared UNIT artwork")
    except (OSError, ValueError, KeyError, IndexError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
