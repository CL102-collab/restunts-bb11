#!/usr/bin/env python3
"""Embed the portable Metal shader source for macOS runtime compilation."""

import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src/restunts/c/renderer/gpu_raster.metal"
HEADER = SOURCE.with_name("gpu_raster_metal.h")
MAX_LITERAL_COLUMNS = 92


def generated_header():
    source = SOURCE.read_text(encoding="utf-8")
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    lines = ["/* Generated by tools/scripts/compile-metal-raster.py; do not edit.",
             f" * Shader SHA-256: {digest} */",
             "#ifndef RESTUNTS_GPU_RASTER_METAL_H", "#define RESTUNTS_GPU_RASTER_METAL_H", "",
             '#include "../legacy.h"', "",
             "static const legacy_char gpu_raster_metal_source[] ="]
    for line in source.splitlines(keepends=True):
        while line:
            count = len(line)
            while len(json.dumps(line[:count], ensure_ascii=True)) > MAX_LITERAL_COLUMNS:
                count -= 1
            lines.append("\t" + json.dumps(line[:count], ensure_ascii=True))
            line = line[count:]
    lines[-1] += ";"
    lines += ["", "#endif", ""]
    return "\r\n".join(lines).encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Check that the complete embedded source matches gpu_raster.metal")
    args = parser.parse_args()
    expected = generated_header()
    if args.check:
        if not HEADER.is_file() or HEADER.read_bytes().replace(b"\r\n", b"\n") != expected.replace(b"\r\n", b"\n"):
            parser.error("Metal shader header is stale; run tools/scripts/compile-metal-raster.py")
        print("Metal shader source and generated header are current.")
        return
    HEADER.write_bytes(expected)


if __name__ == "__main__":
    main()
